function rangeStart(range, now) {
  const DAY = 86400000;
  if (range === "hoje") {
    const d = new Date(now);
    d.setHours(0, 0, 0, 0);
    return d.getTime();
  }
  if (range === "7") return now - 7 * DAY;
  if (range === "30") return now - 30 * DAY;
  return 0;
}


